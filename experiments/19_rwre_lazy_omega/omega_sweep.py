"""Pilots and local slopes of `rwre_gpu_lazy` over p in [0, 1/2], on the ladder and n
that a 2h autopilot at p = 0 chose.

Experiment 19 (user, 2026-10-03). The autopilot's study (`--from-study`) must have drawn
its final run. Its accepted plan fixes three things and nothing else: the top scale K,
n per scale, and the replicate count. Each p then gets one `src/study/pilot.py` study on
the dyadic ladder 4..K at that flat n, and its replicate means go through
`tools/local_slope.analyse` at rho = 2 (16's and 17's pattern). There is no exact
reference for rwre, so unlike 17 there is no check column.

What is read per p (no hypothesis is scored, user 2026-10-03: "just measure"):
  - the pilot's own eq. (232) fit on the whole ladder (pilot.json's direct_fit, omega1's
    se from constants.json);
  - (P) gamma + c k^-omega and (L) gamma + c / ln k on the drawn s_k, whole ladder and
    tail k >= --tail.

A p whose study already holds `pilot.json` is not redrawn, so rerunning the same command
resumes an interrupted sweep.

    python3 experiments/19_rwre_lazy_omega/omega_sweep.py --from-study autopilot_p0 \\
        --tag ap2h --seed 20261004
"""

from __future__ import annotations

import argparse
import json
import math
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

EXP = Path(__file__).resolve().parent
ROOT = EXP.parents[1]
sys.path.insert(0, str(ROOT))
from tools import local_slope as LS  # noqa: E402

P_GRID = [0.0, 0.05, 0.1, 0.15, 0.2, 0.25, 0.3, 0.35, 0.4, 0.45, 0.5]
RHO = 2.0
#: Even k only: on odd k the parity makes E|X_k| jump (16_rwre_hump's smoke run).
K_MIN = 4


def label(p: float) -> str:
    return f"{p:.4g}"


def from_autopilot(sd: Path) -> tuple[list[int], int, int]:
    """(ladder 4..K, n, R) from a finished autopilot study; refuses one that drew nothing."""
    ap = json.loads((sd / "autopilot.json").read_text())
    if not ap.get("drawn") or ap.get("forced"):
        raise SystemExit(f"{sd}: the autopilot did not draw an unforced final run "
                         f"(drawn={ap.get('drawn')}, forced={ap.get('forced')}). "
                         f"Nothing to reuse; re-plan with the user.")
    plan = json.loads((sd / "plan.json").read_text())
    top = int(max(plan["scales"]))
    j = round(math.log2(top))
    if 2 ** j != top:
        raise SystemExit(f"{sd}: top scale {top} is not a power of 2, so 4..K is not dyadic")
    n = plan["n"]
    if not isinstance(n, int):
        raise SystemExit(f"{sd}: plan n is {n!r}, not one flat n per scale")
    return [2 ** i for i in range(2, j + 1)], n, int(plan["replicates"])


def write_recipe(p: float, scales: list[int], n: int, seed: int, source: str) -> Path:
    recipe = {
        "kind": "samples",
        "model": "rwre_gpu_lazy",
        "params": {"p": p, "alpha": 0.5},
        "scales": scales,
        "n": n,
        "seed": seed,
        "_note": ["GENERATED by experiments/19_rwre_lazy_omega/omega_sweep.py from "
                  f"{source}'s accepted plan. Edit the script, not this file."],
    }
    path = EXP / "recipes" / f"samples_omega_p{label(p)}.json"
    path.write_text(json.dumps(recipe, indent=2) + "\n")
    return path


def run_pilot(recipe: Path, study: str, data: Path, replicates: int, seed: int) -> None:
    log = data / f"{study}.log"
    cmd = [sys.executable, str(ROOT / "src/study/pilot.py"), "-meta", str(recipe),
           "--study", study, "--data-root", str(data), "--replicates", str(replicates),
           "--seed", str(seed), "--reuse-cost"]
    print(f"[omega] {study}: log -> {log}", flush=True)
    t0 = time.monotonic()
    with log.open("w") as fh:
        code = subprocess.run(cmd, cwd=ROOT, stdout=fh, stderr=subprocess.STDOUT).returncode
    print(f"[omega] {study}: exit {code} after {time.monotonic() - t0:.0f} s", flush=True)
    if code != 0:
        raise RuntimeError(f"{study}: pilot.py exited {code}; see {log}")


def analyse_p(sd: Path, tail: int) -> dict:
    pilot = json.loads((sd / "pilot.json").read_text())
    consts = json.loads((sd / "constants.json").read_text())
    scales = pilot["scales"]
    reps = pilot["per_replicate"]
    n = pilot["n"]
    ns = n if isinstance(n, list) else [n] * len(scales)
    y_by_scale = [[r["y_bar"][j] for r in reps] for j in range(len(scales))]
    cv = [float(np.mean([r["cv"][j] for r in reps])) for j in range(len(scales))]
    res = LS.analyse(scales, y_by_scale, RHO, cv=cv, n=ns)
    lower = np.asarray(scales[:-1], float)
    s, se = np.asarray(res["s"]), np.asarray(res["se_s_clt"])
    t = lower >= tail
    fits = {"P_all": LS.fit_power(lower, s, se), "L_all": LS.fit_log(lower, s, se),
            "P_tail": LS.fit_power(lower[t], s[t], se[t]) if t.sum() >= 4 else None,
            "L_tail": LS.fit_log(lower[t], s[t], se[t]) if t.sum() >= 3 else None}
    return {"scales": scales, "n": ns[0], "R": len(reps), "s": s.tolist(), "se": se.tolist(),
            "y_bar": pilot["y_bar"], "sigma_log": pilot["sigma_log"],
            "direct_fit": pilot["direct_fit"], "omega1_se": consts["omega1"]["se"],
            "drawn_seconds": pilot["drawn_seconds"], "fits": fits}


def plot_fits(results: dict, out: Path) -> None:
    """log2 Ybar_i (± se) with each p's eq. (232) fit, as 17's pilot_fit figure."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(8, 6))
    cmap = plt.get_cmap("viridis")
    ps = sorted(results)
    for t, p in enumerate(ps):
        r, f = results[p], results[p]["direct_fit"]
        c = cmap(t / max(len(ps) - 1, 1))
        i = np.log2(r["scales"])
        # sigma_log is the se of ln Ybar; the plot is in log2.
        ax.errorbar(i, np.log2(r["y_bar"]), yerr=np.asarray(r["sigma_log"]) / math.log(2),
                    color=c, marker="o", ms=4, lw=0,
                    label=f"p={label(p)}: γ={f['gamma']:.3f}, ω₁={f['omega1']:.3f}±{r['omega1_se']:.3f}")
        ii = np.linspace(i[0] - 0.3, i[-1] + 0.3, 200)
        # fit_correction's a0 is multiplicative and a1 is in ln units (loglog_plot.fit_plot).
        ax.plot(ii, f["gamma"] * ii + math.log2(f["a0"]) + f["a1"] / math.log(2) * 2.0 ** (-f["omega1"] * ii),
                color=c, lw=0.8)
    ax.set(xlabel=r"$i=\log_2(k)$", ylabel=r"$\log_2\overline{Y}_i$",
           title=r"pilot fits: $\log_2\overline{Y}_i$ (± se) and $f(i)=\gamma i+a_0+a_1 2^{-\omega_1 i}$")
    ax.grid(True, color="#e1e0d9", lw=0.6)
    ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(out, dpi=130)


def plot_slopes(results: dict, out: Path) -> None:
    """Drawn local slopes s_k (± CLT se) at the lower scale of each pair."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(8, 6))
    cmap = plt.get_cmap("viridis")
    ps = sorted(results)
    for t, p in enumerate(ps):
        r = results[p]
        ax.errorbar(r["scales"][:-1], r["s"], yerr=r["se"], color=cmap(t / max(len(ps) - 1, 1)),
                    marker="o", ms=4, lw=1, label=f"p={label(p)}")
    ax.set_xscale("log", base=2)
    ax.set(xlabel="k (lower scale of the pair)", ylabel="s_k", title="drawn local slopes s_k (± se)")
    ax.grid(True, color="#e1e0d9", lw=0.6)
    ax.legend(fontsize=7, ncol=2)
    fig.tight_layout()
    fig.savefig(out, dpi=130)


def _fmt_fit(f: dict | None, key: str = "omega") -> str:
    if f is None:
        return "-"
    p = "n/a" if f["p_value"] is None else f"{f['p_value']:.2g}"
    if key == "omega":
        se = f" ± {f['se_omega']:.3f}" if "se_omega" in f else ""
        return (f"γ={f['gamma']:.4f}, ω={f['omega']:.3f}{se}{' [bound]' if f['omega_on_bound'] else ''}, "
                f"χ²={f['chi2']:.1f}/{f['dof']}, p={p}")
    return f"γ={f['gamma']:.4f}, χ²={f['chi2']:.1f}/{f['dof']}, p={p}"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--from-study", required=True, dest="from_study",
                    help="the finished autopilot study whose plan sets K, n and R")
    ap.add_argument("--tag", required=True, help="study name suffix: omega_p<p>_<tag>")
    ap.add_argument("--seed", type=int, required=True, help="base seed; p number t gets seed + t")
    ap.add_argument("--p", type=float, nargs="+", default=P_GRID)
    ap.add_argument("--tail", type=int, default=256, help="smallest k of the tail fits")
    ap.add_argument("--data-root", type=Path, default=EXP / "data")
    args = ap.parse_args()
    data = args.data_root.resolve()
    scales, n, R = from_autopilot(data / args.from_study)
    print(f"[omega] from {args.from_study}: ladder {scales[0]}..{scales[-1]}, n = {n:,} x {R}",
          flush=True)

    results = {}
    for ip, p in enumerate(args.p):
        study = f"omega_p{label(p)}_{args.tag}"
        seed = args.seed + ip
        if not (data / study / "pilot.json").exists():
            run_pilot(write_recipe(p, scales, n, seed, args.from_study), study, data, R, seed)
        results[p] = analyse_p(data / study, args.tail)

    plot_fits(results, data / f"pilot_fit_{args.tag}.png")
    plot_slopes(results, data / f"slopes_{args.tag}.png")
    lines = [
        f"# rwre_gpu_lazy correction exponent across p, tag `{args.tag}`: ladder "
        f"{scales[0]}..{scales[-1]}, n = {n:,} × {R} per scale (from `{args.from_study}`)",
        "",
        "eq. (232) = pilot.py's own fit on the whole ladder (ω₁ se from constants.json). "
        "s_k sits at its lower scale k; se is the CLT's (`local_slope.clt_se`).",
        "",
        f"| p | eq. (232) γ, ω₁ | (P) all | (L) all | (P) k ≥ {args.tail} | (L) k ≥ {args.tail} | draw min |",
        "|---|---|---|---|---|---|---|",
    ]
    for p in sorted(results):
        r, f, d = results[p], results[p]["fits"], results[p]["direct_fit"]
        lines.append(
            f"| {label(p)} | γ={d['gamma']:.4f}, ω₁={d['omega1']:.3f} ± {r['omega1_se']:.3f}"
            f"{'' if d['converged'] else ' (not converged)'} | {_fmt_fit(f['P_all'])} "
            f"| {_fmt_fit(f['L_all'], 'gamma')} | {_fmt_fit(f['P_tail'])} "
            f"| {_fmt_fit(f['L_tail'], 'gamma')} | {r['drawn_seconds'] / 60:.1f} |")
    lines += ["", "## drawn s_k ± se", ""]
    for p in sorted(results):
        r = results[p]
        lines.append(f"- p={label(p)}: " + ", ".join(
            f"{k}: {v:.4f}±{e:.4f}" for k, v, e in zip(r["scales"], r["s"], r["se"])))
    text = "\n".join(lines) + "\n"
    (data / f"omega_{args.tag}.md").write_text(text)
    (data / f"omega_{args.tag}.json").write_text(json.dumps(
        {"produced_by": "experiments/19_rwre_lazy_omega/omega_sweep.py",
         "args": vars(args) | {"data_root": str(data)},
         "ladder": scales, "n": n, "replicates": R,
         "results": {label(p): r for p, r in results.items()}}, indent=1, default=str))
    print(text + f"\n[omega] figures -> {data}/pilot_fit_{args.tag}.png, slopes_{args.tag}.png",
          flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
