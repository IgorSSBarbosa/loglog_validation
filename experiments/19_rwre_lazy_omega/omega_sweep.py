"""Pilots and local slopes of `rwre_gpu_lazy` over p in [0, 1/2], on the ladder and n
that a 2h autopilot at p = 0 chose.

Experiment 19 (user, 2026-10-03). The autopilot's study (`--from-study`) must have drawn
its final run. Its accepted plan fixes three things and nothing else: the top scale K,
n per scale, and the replicate count. Each p then gets one `src/study/pilot.py` study on
the dyadic ladder 4..K at that flat n, and its replicate means go through
`tools/local_slope.analyse` at rho = 2 (16's and 17's pattern). There is no exact
reference for rwre, so unlike 17 there is no check column.

What is read per p (no hypothesis is scored, user 2026-10-03: "just measure"):
  - the pilot's own eq. (232) fit on the whole ladder (pilot.json's direct_fit, omega1's
    se from constants.json);
  - (P) gamma + c k^-omega and (L) gamma + c / ln k on the drawn s_k, whole ladder and
    tail k >= --tail.

A p whose study already holds `pilot.json` is not redrawn, so rerunning the same command
resumes an interrupted sweep.

`--n` and `--top` override the plan's n and K (user, 2026-10-05: n = 800,000 x 5 to match
16's se, 4..2^20 for p >= 0.35 and 4..2^18 below, split over three hosts). Each p's seed
is --seed + its index in P_GRID, so hosts that run disjoint --p lists draw what one host
running the whole grid would. `--analyse-only` then pools the finished studies, each on
its own ladder, without drawing anything.

    python3 experiments/19_rwre_lazy_omega/omega_sweep.py --from-study autopilot_p0 \\
        --tag ap2h --seed 20261004
"""

