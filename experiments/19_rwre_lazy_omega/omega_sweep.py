P_GRID = [0.0, 0.05, 0.1, 0.15, 0.2, 0.25, 0.3, 0.35, 0.4, 0.45, 0.5]
RHO = 2.0
#: Even k only: on odd k the parity makes E|X_k| jump (16_rwre_hump's smoke run).
K_MIN = 4
#: Block length (in rungs) of omega_eff's two differences.
OMEGA_EFF_M = 2


def label(p: float) -> str:
    return f"{p:.4g}"


def from_autopilot(sd: Path) -> tuple[list[int], int, int]:
    """(ladder 4..K, n, R) from a finished autopilot study; refuses one that drew nothing."""
    ap = json.loads((sd / "autopilot.json").read_text())
    if not ap.get("drawn") or ap.get("forced"):
        raise SystemExit(f"{sd}: the autopilot did not draw an unforced final run "
                         f"(drawn={ap.get('drawn')}, forced={ap.get('forced')}). "
                         f"Nothing to reuse; re-plan with the user.")
    plan = json.loads((sd / "plan.json").read_text())
    top = int(max(plan["scales"]))
    j = round(math.log2(top))
    if 2 ** j != top:
        raise SystemExit(f"{sd}: top scale {top} is not a power of 2, so 4..K is not dyadic")
    n = plan["n"]
    if not isinstance(n, int):
        raise SystemExit(f"{sd}: plan n is {n!r}, not one flat n per scale")
    return [2 ** i for i in range(2, j + 1)], n, int(plan["replicates"])


def write_recipe(p: float, scales: list[int], n: int, seed: int, source: str,
                 tag: str) -> Path:
    recipe = {
        "kind": "samples",
        "model": "rwre_gpu_lazy",
        "params": {"p": p, "alpha": 0.5},
        "scales": scales,
        "n": n,
        "seed": seed,
        "_note": ["GENERATED by experiments/19_rwre_lazy_omega/omega_sweep.py from "
                  f"{source}'s accepted plan (tag {tag}). Edit the script, not this file."],
    }
    path = EXP / "recipes" / f"samples_omega_p{label(p)}_{tag}.json"
    path.write_text(json.dumps(recipe, indent=2) + "\n")
    return path


def run_pilot(recipe: Path, study: str, data: Path, replicates: int, seed: int) -> None:
    log = data / f"{study}.log"
    cmd = [sys.executable, str(ROOT / "src/study/pilot.py"), "-meta", str(recipe),
           "--study", study, "--data-root", str(data), "--replicates", str(replicates),
           "--seed", str(seed), "--reuse-cost"]
    print(f"[omega] {study}: log -> {log}", flush=True)
    t0 = time.monotonic()
    with log.open("w") as fh:
        code = subprocess.run(cmd, cwd=ROOT, stdout=fh, stderr=subprocess.STDOUT).returncode
    print(f"[omega] {study}: exit {code} after {time.monotonic() - t0:.0f} s", flush=True)
    if code != 0:
        raise RuntimeError(f"{study}: pilot.py exited {code}; see {log}")


def analyse_p(sd: Path, tail: int) -> dict:
    pilot = json.loads((sd / "pilot.json").read_text())
    consts = json.loads((sd / "constants.json").read_text())
    scales = pilot["scales"]
    reps = pilot["per_replicate"]
    n = pilot["n"]
    ns = n if isinstance(n, list) else [n] * len(scales)
    y_by_scale = [[r["y_bar"][j] for r in reps] for j in range(len(scales))]
    cv = [float(np.mean([r["cv"][j] for r in reps])) for j in range(len(scales))]
    res = LS.analyse(scales, y_by_scale, RHO, cv=cv, n=ns)
    lower = np.asarray(scales[:-1], float)
    s, se = np.asarray(res["s"]), np.asarray(res["se_s_clt"])
    t = lower >= tail
    fits = {"P_all": LS.fit_power(lower, s, se), "L_all": LS.fit_log(lower, s, se),
            "P_tail": LS.fit_power(lower[t], s[t], se[t]) if t.sum() >= 4 else None,
            "L_tail": LS.fit_log(lower[t], s[t], se[t]) if t.sum() >= 3 else None}
    return {"scales": scales, "n": ns[0], "R": len(reps), "s": s.tolist(), "se": se.tolist(),
            "cv": cv, "y_bar": pilot["y_bar"], "sigma_log": pilot["sigma_log"],
            "direct_fit": pilot["direct_fit"], "omega1_se": consts["omega1"]["se"],
            "drawn_seconds": pilot["drawn_seconds"], "fits": fits}


def plot_fits(results: dict, out: Path) -> None:
    """log2 Ybar_i (± se) with each p's eq. (232) fit, as 17's pilot_fit figure."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(8, 6))
    cmap = plt.get_cmap("viridis")
    ps = sorted(results)
    for t, p in enumerate(ps):
        r, f = results[p], results[p]["direct_fit"]
        c = cmap(t / max(len(ps) - 1, 1))
        i = np.log2(r["scales"])
        # sigma_log is the se of ln Ybar; the plot is in log2.
        ax.errorbar(i, np.log2(r["y_bar"]), yerr=np.asarray(r["sigma_log"]) / math.log(2),
                    color=c, marker="o", ms=4, lw=0,
                    label=f"p={label(p)}: γ={f['gamma']:.3f}, ω₁={f['omega1']:.3f}±{r['omega1_se']:.3f}")
        ii = np.linspace(i[0] - 0.3, i[-1] + 0.3, 200)
        # fit_correction's a0 is multiplicative and a1 is in ln units (loglog_plot.fit_plot).
        ax.plot(ii, f["gamma"] * ii + math.log2(f["a0"]) + f["a1"] / math.log(2) * 2.0 ** (-f["omega1"] * ii),
                color=c, lw=0.8)
    ax.set(xlabel=r"$i=\log_2(k)$", ylabel=r"$\log_2\overline{Y}_i$",
           title=r"pilot fits: $\log_2\overline{Y}_i$ (± se) and $f(i)=\gamma i+a_0+a_1 2^{-\omega_1 i}$")
    ax.grid(True, color="#e1e0d9", lw=0.6)
    ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(out, dpi=130)


