"""Pilots and local slopes of `erw_urn_gpu` over a grid of p, to read the correction
exponent omega of E|S_k| on each side of p = 3/4.

Experiment 17 (user, 2026-09-30). For each p, one `src/study/pilot.py` study on one
dyadic ladder 4..2^20 at a flat n, and its replicate means through
`tools/local_slope.analyse` at rho = 2. Next to it, the EXACT E|S_k| on the same ladder
up to --exact-max, from eq. (2.2)'s chain by dynamic programming: its slopes are the
n = infinity limit of the pilot's, so they check the draws (|z| per slope) and give a
noise-free local exponent w_k where the chain is affordable.

What is read per p, none of it told any hypothesis (ground rule 4, the hypotheses and
their scoring live in the README):
  - w_k = -log2(Delta s_{k+1} / Delta s_k), exact and drawn: flat at omega under a single
    power law, drifting to 0 under a 1/log k correction;
  - (P) gamma + c k^-omega and (L) gamma + c / ln k on the drawn s_k, on the whole ladder
    and on its tail k >= --tail;
  - (2P) gamma + c1 / k + c2 k^-omega on the drawn s_k, omega free.

A p whose study already holds `pilot.json` is not redrawn, and an exact law already
cached is not recomputed, so rerunning the same command resumes an interrupted run.

    python3 experiments/17_erw_omega/omega_sweep.py --tag n8m --seed 20260930
"""

