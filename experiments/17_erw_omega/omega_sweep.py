P_GRID = [0.1, 0.25, 0.4, 0.5, 0.55, 0.6, 0.65, 0.7, 0.75, 0.8, 0.85, 0.9, 0.95]
#: Dyadic and even: on odd k the parity makes E|S_k| jump (16_rwre_hump's smoke run).
SCALES = [2 ** j for j in range(2, 21)]
RHO = 2.0


def label(p: float) -> str:
    return f"{p:.4g}"


def write_recipe(p: float, n: int, seed: int) -> Path:
    recipe = {
        "kind": "samples",
        "model": "erw_urn_gpu",
        "params": {"p": p},
        "scales": SCALES,
        "n": n,
        "seed": seed,
        "_note": ["GENERATED by experiments/17_erw_omega/omega_sweep.py. Edit the script, not this file."],
    }
    path = EXP / "recipes" / f"samples_omega_p{label(p)}.json"
    path.parent.mkdir(exist_ok=True)
    path.write_text(json.dumps(recipe, indent=2) + "\n")
    return path


def run_pilot(recipe: Path, study: str, data: Path, replicates: int, seed: int) -> None:
    data.mkdir(parents=True, exist_ok=True)
    log = data / f"{study}.log"
    cmd = [sys.executable, str(ROOT / "src/study/pilot.py"), "-meta", str(recipe),
           "--study", study, "--data-root", str(data), "--replicates", str(replicates),
           "--seed", str(seed), "--reuse-cost"]
    print(f"[omega] {study}: log -> {log}", flush=True)
    t0 = time.monotonic()
    with log.open("w") as fh:
        code = subprocess.run(cmd, cwd=ROOT, stdout=fh, stderr=subprocess.STDOUT).returncode
    print(f"[omega] {study}: exit {code} after {time.monotonic() - t0:.0f} s", flush=True)
    if code != 0:
        raise RuntimeError(f"{study}: pilot.py exited {code}; see {log}")


def exact_abs_mean(p: float, ks: list[int]) -> dict[int, float]:
    """E|S_k| at each k in ks, exactly, from eq. (2.2)'s chain (Bercu 2018).

    X_1 = +-1 fairly, then P(X_{n+1} = +1 | S_n) = (1 + (2p - 1) S_n / n) / 2. One pass
    to max(ks), O(max(ks)^2) work; only the support |S| <= n is touched at step n.
    """
    K = max(ks)
    s = np.arange(-K, K + 1, dtype=float)
    prob = np.zeros(2 * K + 1)
    prob[K - 1] = prob[K + 1] = 0.5
    want, out = set(ks), {}
    for n in range(1, K):
        if n in want:
            out[n] = float(prob @ np.abs(s))
        lo, hi = K - n, K + n + 1
        pr = prob[lo:hi].copy()
        up = 0.5 * (1.0 + (2 * p - 1) * s[lo:hi] / n)
        moved = np.zeros(hi - lo + 2)
        moved[2:] += pr * up
        moved[:-2] += pr * (1.0 - up)
        prob[lo - 1:hi + 1] = moved
    out[K] = float(prob @ np.abs(s))
    return out


def exact_cached(p: float, kmax: int, data: Path) -> dict[int, float]:
    path = data / f"exact_p{label(p)}_k{kmax}.json"
    if path.exists():
        return {int(k): v for k, v in json.loads(path.read_text())["mean_abs"].items()}
    ks = [k for k in SCALES if k <= kmax]
    t0 = time.monotonic()
    out = exact_abs_mean(p, ks)
    sec = time.monotonic() - t0
    path.write_text(json.dumps({"produced_by": "experiments/17_erw_omega/omega_sweep.py",
                                "p": p, "seconds": sec, "mean_abs": out}, indent=1))
    print(f"[omega] exact p={label(p)} to k={kmax}: {sec:.0f} s", flush=True)
    return out


def slopes_and_w(log_y: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """s_k, Delta s_k and w_k from noiseless log means (nan where Delta s changes sign)."""
    s = np.diff(log_y) / math.log(RHO)
    ds = np.diff(s)
    with np.errstate(invalid="ignore", divide="ignore"):
        w = -np.log(ds[1:] / ds[:-1]) / math.log(RHO)
    return s, ds, w


def fit_two_power(k, s, se, omega_bounds=(0.02, 3.0)) -> dict:
    """(2P) s = gamma + c1 / k + c2 k^-omega, weighted, omega profiled.

    The conjecture's shape with omega left free. se(omega) from the profile's
    Delta chi2 = 1 crossings, which is honest when the profile is not parabolic.
    """
    k, s, se = (np.asarray(v, float) for v in (k, s, se))

    def profile(om: float):
        A = np.vstack([np.ones_like(k), 1 / k, k ** -om]).T / se[:, None]
        coef, *_ = np.linalg.lstsq(A, s / se, rcond=None)
        r = A @ coef - s / se
        return float(r @ r), coef

    grid = np.geomspace(*omega_bounds, 600)
    chi = np.array([profile(o)[0] for o in grid])
    j = int(np.argmin(chi))
    lo, hi = grid[max(j - 1, 0)], grid[min(j + 1, grid.size - 1)]
    om = float(optimize.minimize_scalar(lambda o: profile(o)[0], bounds=(lo, hi),
                                        method="bounded", options={"xatol": 1e-8}).x)
    chi2, (g, c1, c2) = profile(om)
    inside = grid[chi <= chi2 + 1.0]
    dof = k.size - 4
    return {"gamma": float(g), "c1": float(c1), "c2": float(c2), "omega": om,
            "omega_lo": float(inside.min()), "omega_hi": float(inside.max()),
            "on_bound": bool(j in (0, grid.size - 1)), "chi2": chi2, "dof": dof,
            "p_value": float(stats.chi2.sf(chi2, dof)) if dof > 0 else None}


def analyse_p(pilot: dict, exact: dict[int, float], tail: int) -> dict:
    scales = pilot["scales"]
    reps = pilot["per_replicate"]
    n = pilot["n"]
    ns = n if isinstance(n, list) else [n] * len(scales)
    y_by_scale = [[r["y_bar"][j] for r in reps] for j in range(len(scales))]
    cv = [float(np.mean([r["cv"][j] for r in reps])) for j in range(len(scales))]
    res = LS.analyse(scales, y_by_scale, RHO, cv=cv, n=ns)
    lower = np.asarray(scales[:-1], float)
    s, se = np.asarray(res["s"]), np.asarray(res["se_s_clt"])

    ke = [k for k in scales if k in exact]
    s_e, ds_e, w_e = slopes_and_w(np.log([exact[k] for k in ke]))
    m = len(s_e)
    z = (s[:m] - s_e) / se[:m]

    t = lower >= tail
    fits = {"P_all": LS.fit_power(lower, s, se), "L_all": LS.fit_log(lower, s, se),
            "P_tail": LS.fit_power(lower[t], s[t], se[t]) if t.sum() >= 4 else None,
            "L_tail": LS.fit_log(lower[t], s[t], se[t]) if t.sum() >= 3 else None,
            "2P_all": fit_two_power(lower, s, se)}
    return {"scales": scales, "n": ns[0], "R": len(reps), "s": s.tolist(), "se": se.tolist(),
            "ds": res["ds"], "se_ds": res["se_ds"], "w": res["w"], "se_w": res["se_w"],
            "w_resolved": res["w_resolved"],
            "exact": {"k": ke, "mean_abs": [exact[k] for k in ke], "s": s_e.tolist(),
                      "ds": ds_e.tolist(), "w": [None if not np.isfinite(v) else float(v) for v in w_e]},
            "check": {"z": z.tolist(), "max_abs_z": float(np.max(np.abs(z))),
                      "chi2": float(z @ z), "dof": int(m),
                      "p_value": float(stats.chi2.sf(z @ z, m))},
            "fits": fits}


def plot(results: dict, out: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, axes = plt.subplots(1, 3, figsize=(17, 5.2))
    cmap = plt.get_cmap("viridis")
    ps = sorted(results)
    for t, p in enumerate(ps):
        r = results[p]
        c = cmap(t / max(len(ps) - 1, 1))
        lower = np.asarray(r["scales"][:-1], float)
        axes[0].errorbar(lower, r["s"], yerr=r["se"], color=c, marker="o", ms=3, lw=0.8,
                         label=f"p={label(p)}")
        ke = np.asarray(r["exact"]["k"][:-1], float)
        axes[0].plot(ke, r["exact"]["s"], color=c, lw=0, marker="x", ms=4)
        ds, se_ds = np.abs(r["ds"]), np.asarray(r["se_ds"])
        ok = ds > 2 * se_ds
        axes[1].errorbar(lower[:-1][ok], ds[ok], yerr=se_ds[ok], color=c, marker="o", ms=3, lw=0)
        axes[1].plot(ke[:-1], np.abs(r["exact"]["ds"]), color=c, lw=1)
        w_e = np.array([np.nan if v is None else v for v in r["exact"]["w"]], float)
        axes[2].plot(ke[:-2] * 2, w_e, color=c, marker=".", lw=1, label=f"p={label(p)}")
    axes[0].set(xscale="log", xlabel="k (lower scale of the pair)", ylabel="s_k",
                title="(a) local slopes: drawn (o, ± se) and exact (x)")
    axes[0].set_xscale("log", base=2)
    axes[0].legend(fontsize=7, ncol=2)
    axes[1].set(xscale="log", yscale="log", xlabel="k", ylabel="|Δs_k|",
                title="(b) |Δs_k|: drawn (o, resolved only) and exact (line);\nslope = -ω")
    axes[1].set_xscale("log", base=2)
    axes[2].set(xscale="log", xlabel="k (middle scale)", ylabel="w_k",
                title="(c) exact local exponent w_k = -log2(Δs_{k+1}/Δs_k)")
    axes[2].set_xscale("log", base=2)
    axes[2].set_ylim(-0.1, 2.0)
    for a in axes:
        a.grid(True, color="#e1e0d9", lw=0.6)
    fig.tight_layout()
    fig.savefig(out, dpi=130)


def _fmt_fit(f: dict | None, key: str = "omega") -> str:
    if f is None:
        return "-"
    p = "n/a" if f["p_value"] is None else f"{f['p_value']:.2g}"
    if key == "omega":
        se = f" ± {f['se_omega']:.3f}" if "se_omega" in f else ""
        return f"ω={f['omega']:.3f}{se}{' [bound]' if f['omega_on_bound'] else ''}, χ²={f['chi2']:.1f}/{f['dof']}, p={p}"
    return f"γ={f['gamma']:.4f}, χ²={f['chi2']:.1f}/{f['dof']}, p={p}"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--tag", required=True, help="study name suffix: omega_p<p>_<tag>")
    ap.add_argument("--seed", type=int, required=True, help="base seed; p number t gets seed + t")
    ap.add_argument("--n", type=int, default=2 ** 23, help="draws per scale per replicate")
    ap.add_argument("--replicates", type=int, default=4)
    ap.add_argument("--p", type=float, nargs="+", default=P_GRID)
    ap.add_argument("--exact-max", type=int, default=2 ** 16, dest="exact_max",
                    help="top of the exact ladder (a power of 2 in SCALES); O(k^2) CPU")
    ap.add_argument("--tail", type=int, default=256, help="smallest k of the tail fits")
    ap.add_argument("--data-root", type=Path, default=EXP / "data")
    args = ap.parse_args()
    if args.exact_max not in SCALES:
        raise SystemExit(f"--exact-max {args.exact_max} is not on the ladder {SCALES}")
    data = args.data_root.resolve()
    data.mkdir(parents=True, exist_ok=True)

    results = {}
    for ip, p in enumerate(args.p):
        study = f"omega_p{label(p)}_{args.tag}"
        seed = args.seed + ip
        if not (data / study / "pilot.json").exists():
            run_pilot(write_recipe(p, args.n, seed), study, data, args.replicates, seed)
        pilot = json.loads((data / study / "pilot.json").read_text())
        results[p] = analyse_p(pilot, exact_cached(p, args.exact_max, data), args.tail)

    plot(results, data / f"omega_{args.tag}.png")
    r0 = results[args.p[0]]
    lines = [
        f"# erw_urn_gpu correction exponent, tag `{args.tag}`: ladder {SCALES[0]}..{SCALES[-1]}, "
        f"n = {r0['n']:,} × {r0['R']} per scale; exact E|S_k| to k = {args.exact_max}",
        "",
        "s_k sits at its lower scale k. se is the CLT's (`local_slope.clt_se`). "
        "`check` = drawn s_k against the exact one, z = (drawn - exact) / se.",
        "",
        "## check and fits",
        "",
        "| p | check χ²/dof (max abs z) | (P) all | (L) all | "
        f"(P) k ≥ {args.tail} | (L) k ≥ {args.tail} | (2P) ω [Δχ²=1 band], χ²/dof |",
        "|---|---|---|---|---|---|---|",
    ]
    for p in sorted(results):
        r, f = results[p], results[p]["fits"]
        c = r["check"]
        tp = f["2P_all"]
        lines.append(
            f"| {label(p)} | {c['chi2']:.1f}/{c['dof']} ({c['max_abs_z']:.1f}) | {_fmt_fit(f['P_all'])} "
            f"| {_fmt_fit(f['L_all'], 'gamma')} | {_fmt_fit(f['P_tail'])} | {_fmt_fit(f['L_tail'], 'gamma')} "
            f"| {tp['omega']:.3f} [{tp['omega_lo']:.3f}, {tp['omega_hi']:.3f}]"
            f"{' [bound]' if tp['on_bound'] else ''}, {tp['chi2']:.1f}/{tp['dof']} |")
    ke = results[args.p[0]]["exact"]["k"]
    mids = [2 * k for k in ke[:-3]]
    lines += ["", "## exact w_k (middle scale of the three)", "",
              "| p | " + " | ".join(str(k) for k in mids) + " |",
              "|---|" + "---|" * len(mids)]
    for p in sorted(results):
        w = results[p]["exact"]["w"]
        lines.append(f"| {label(p)} | " + " | ".join("-" if v is None else f"{v:.3f}" for v in w) + " |")
    lines += ["", "## drawn w_k ± se (? = unresolved)", ""]
    for p in sorted(results):
        r = results[p]
        lines.append(f"- p={label(p)}: " + ", ".join(
            f"{2 * k}: " + ("-" if v is None else f"{v:.2f}±{e:.2f}{'' if ok else '?'}")
            for k, v, e, ok in zip(r["scales"], r["w"], r["se_w"], r["w_resolved"])))
    text = "\n".join(lines) + "\n"
    (data / f"omega_{args.tag}.md").write_text(text)
    (data / f"omega_{args.tag}.json").write_text(json.dumps(
        {"produced_by": "experiments/17_erw_omega/omega_sweep.py",
         "args": vars(args) | {"data_root": str(data)},
         "results": {label(p): r for p, r in results.items()}}, indent=1, default=str))
    print(text + f"\n[omega] figure -> {data / f'omega_{args.tag}.png'}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
