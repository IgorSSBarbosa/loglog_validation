"""Run `autopilot.py` on `rwre_gpu` over a sieve of p on the linear window W = 2k + 100.

Experiment 15 is 13_rwre_gpu's sieve with one change, the window: W = 2k + 100
instead of 12 ceil(k^(3/4)) (user, 2026-09-30). At slope 2 the walker can never
reach the seam of the periodic window, and the offset keeps the environment's
wrap heuristic below e^-50 at every k (models/rwre.py, decision (d)). Same grid
(02_rwre's A6 sieve plus p = 1/3, all in [0, 1/2]), same pilots, same wall clock
per p, so what differs from 13 is the window alone. The pilot recipe for each p
is a template with only `params.p` changed, chosen by `--pilot`:

- `neyman` (default): `recipes/samples_sweep_neyman.json`, a ladder from i = 2
  with n_i ~ i**(-d/2), run with `--max-rounds 9` (13's neyman pilot).
- `snr`: `recipes/samples_calib_p0.5.json` (flat n on 4..1024).

Both templates already carry the window; `write_recipe` refuses one that does not.
The window caps k at 49094, where 2k + 100 fills a block's shared memory, so every
study is given `--max-scale` = models/rwre_gpu.py's `max_steps` (a `--max-scale`
after `--` overrides it): the ladders stop at 2^15, where 13's reached 2^16. A p
whose study already holds `autopilot.json` is skipped, so rerunning the same
command resumes an interrupted sweep, and on a finished sweep it only rewrites the
summary. Arms run sequentially because they share one GPU.

The summary `sweep_p_<tag>.md` holds 13's two tables: gamma_hat, and omega1 as the
pilot measured it next to the final run's refit. There is no true-gamma column:
rwre's gamma is known only at p = 1/2.

    python3 experiments/15_rwre_linear_window/sweep_p.py --tag neyman --time 1h
    python3 experiments/15_rwre_linear_window/sweep_p.py --tag smoke --time 4m --p 0.5 --pilot snr

Anything after `--` is passed to every `autopilot.py` call unchanged, after the
script's own flags, so a `--max-rounds` there overrides the neyman pilot's 9.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from fractions import Fraction
from pathlib import Path

EXP = Path(__file__).resolve().parent
ROOT = EXP.parents[1]
#: --pilot -> (template recipe, autopilot flags the rule needs, generated recipe suffix).
#: The suffixes keep the two pilots' generated recipes apart.
PILOTS = {
    "neyman": (EXP / "recipes" / "samples_sweep_neyman.json",
               ["--max-rounds", "9"], "_neyman_pilot"),
    "snr": (EXP / "recipes" / "samples_calib_p0.5.json", [], "_snr_pilot"),
}

sys.path.insert(0, str(ROOT))
from models.rwre_gpu import max_steps  # noqa: E402

P_GRID = [1 / 3, 0.0, 0.1, 0.2, 0.3, 0.4, 0.45, 0.5]

#: The window rule the sweep runs at, W = window_slope * k + window_offset.
WINDOW = {"window_slope": 2.0, "window_offset": 100.0}


def parse_p(s: str) -> float:
    """A p from the command line; fractions such as 1/3 are accepted."""
    p = float(Fraction(s))
    if not 0.0 <= p <= 1.0:
        raise argparse.ArgumentTypeError(f"p must be in [0, 1]; got {s}")
    return p


def label(p: float) -> str:
    """Short, filename-safe p for study and recipe names: 0.3333, not 0.3333333333333333."""
    return f"{p:.4g}"


def write_recipe(p: float, pilot: str) -> Path:
    template, _, suffix = PILOTS[pilot]
    recipe = json.loads(template.read_text())
    window = {k: recipe["params"].get(k) for k in WINDOW}
    if window != WINDOW:
        raise ValueError(f"{template.name} has window {window}; this sweep runs at {WINDOW}")
    recipe["params"]["p"] = p
    recipe["_note"] = [
        f"GENERATED by experiments/15_rwre_linear_window/sweep_p.py --pilot {pilot}:",
        f"{template.name} with only params.p changed. Edit the template or the script,",
        "not this file.",
    ]
    path = EXP / "recipes" / f"samples_sweep_p{label(p)}{suffix}.json"
    path.write_text(json.dumps(recipe, indent=2) + "\n")
    return path


def ladder(scales: list) -> str:
    return f"{scales[0]}..{scales[-1]} ({len(scales)})"


def per_scale(n: int | list, scales: list) -> list[int]:
    return list(n) if isinstance(n, list) else [n] * len(scales)


def draws(n: int | list, replicates: int, scales: list) -> str:
    """n/scale × reps; a per-scale n (e.g. a neyman pilot) as smallest-scale..largest-scale."""
    ns = per_scale(n, scales)
    each = f"{ns[0]:,}" if len(set(ns)) == 1 else f"{ns[0]:,}..{ns[-1]:,}"
    return f"{each} × {replicates}"


def samples(n: int | list, replicates: int, scales: list) -> str:
    """Samples produced: every replicate draws n_i at each scale i."""
    return f"{sum(per_scale(n, scales)) * replicates:,}"


def summary_rows(p: float, study: str, data: Path, code: int | None) -> tuple[str, str]:
    """(gamma row, omega1 row) for one study."""
    pilot_path = data / study / "pilot.json"
    if pilot_path.exists():
        pilot = json.loads(pilot_path.read_text())
        om = json.loads((data / study / "constants.json").read_text())["omega1"]
        # The converged flag must belong to the fit that produced constants.json's omega1.
        assert pilot["direct_fit"]["omega1"] == om["value"], f"{study}: omega1 not from direct_fit"
        om_pilot = (f"| {label(p)} | {om['value']:.3f} ± {om['se']:.3f} "
                    f"| {pilot['direct_fit']['converged']} "
                    f"| {ladder(pilot['scales'])} | {draws(pilot['n'], pilot['replicates'], pilot['scales'])} "
                    f"| {samples(pilot['n'], pilot['replicates'], pilot['scales'])}")
    else:
        om_pilot = f"| {label(p)} | - | - | - | - | -"
    ap_path = data / study / "autopilot.json"
    if not ap_path.exists():
        # A pilot that gave up without writing autopilot.json still measured omega1,
        # and those gated p's are the ones whose omega1 is worth reading.
        return (f"| {label(p)} | `{study}` | exit {code} | - | - | - | - | - | - |",
                f"{om_pilot} | - | - | - | - | - |")
    ap = json.loads(ap_path.read_text())
    if not ap.get("drawn"):
        return (f"| {label(p)} | `{study}` | not drawn (gate) | - | - | - | - | - "
                f"| {ap['pilot_seconds'] / 60:.1f} |",
                f"{om_pilot} | - | - | - | - | - |")
    answer = json.loads((data / study / "answer.json").read_text())
    # From the artifacts rather than this script's clock, so a resumed sweep's summary
    # still has it.
    final_s = json.loads((data / study / "final.json").read_text())["elapsed_seconds"]
    wall = f"{(ap['pilot_seconds'] + final_s) / 60:.1f}"
    lo, hi = answer["wilson"]["interval"]
    forced = " (forced)" if ap.get("forced") else ""
    final = draws(answer["n"], answer["replicates"], answer["scales"])
    total = samples(answer["n"], answer["replicates"], answer["scales"])
    fit = answer["fit"]
    return ((f"| {label(p)} | `{study}` | drawn{forced} "
             f"| {ap['gamma']:.5f} ± {answer['se']:.5f} | [{lo:.4f}, {hi:.4f}] "
             f"| {answer['scales'][0]}..{answer['scales'][-1]} | {final} | {total} | {wall} |"),
            (f"{om_pilot} | {fit['omega1']:.3f} | {fit['a1']:.3g} "
             f"| {ladder(answer['scales'])} | {final} | {total} |"))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--tag", required=True, help="study name suffix: sweep_p<p>_<tag>")
    ap.add_argument("--time", default="1h", help="autopilot --time for EACH p (default 1h)")
    ap.add_argument("--p", type=parse_p, nargs="+", default=P_GRID,
                    help="p values, run in this order; fractions like 1/3 are accepted")
    ap.add_argument("--data-root", type=Path, default=EXP / "data",
                    help="where the studies live (default: this experiment's data/)")
    ap.add_argument("--pilot", choices=sorted(PILOTS), default="neyman",
                    help="the pilot's recipe template (default neyman; see the module docstring)")
    ap.add_argument("autopilot_args", nargs=argparse.REMAINDER,
                    help="after `--`: extra arguments for every autopilot.py call")
    args = ap.parse_args()
    extra = [a for a in args.autopilot_args if a != "--"]

    data = args.data_root.resolve()
    rows = []
    failed = []
    for p in args.p:
        study = f"sweep_p{label(p)}_{args.tag}"
        if (data / study / "autopilot.json").exists():
            print(f"[sweep] p={label(p)}: {study} already finished, skipping", flush=True)
            rows.append((p, summary_rows(p, study, data, None)))
            continue
        recipe = write_recipe(p, args.pilot)
        max_scale = max_steps(json.loads(recipe.read_text())["params"])
        data.mkdir(parents=True, exist_ok=True)
        log = data / f"{study}.log"
        cmd = [sys.executable, str(ROOT / "src/study/autopilot.py"), "-meta", str(recipe),
               "--study", study, "--data-root", str(data), "--time", args.time,
               "--max-scale", str(max_scale), "--no-progress", *PILOTS[args.pilot][1], *extra]
        print(f"[sweep] p={label(p)}: {' '.join(cmd)}\n[sweep]   log -> {log}", flush=True)
        t0 = time.monotonic()
        # tee by hand: the log must survive a crash of this script, and the terminal
        # should still show the phase lines live.
        with log.open("w") as fh:
            proc = subprocess.Popen(cmd, cwd=ROOT, stdout=subprocess.PIPE,
                                    stderr=subprocess.STDOUT, text=True)
            for line in proc.stdout:
                sys.stdout.write(line)
                fh.write(line)
                fh.flush()
            code = proc.wait()
        minutes = (time.monotonic() - t0) / 60
        print(f"[sweep] p={label(p)}: exit {code} after {minutes:.1f} min", flush=True)
        rows.append((p, summary_rows(p, study, data, code)))
        if code != 0:
            failed.append(label(p))

    rows = [r for _, r in sorted(rows, key=lambda t: t[0])]
    table = "\n".join([
        f"# rwre_gpu p sweep, tag `{args.tag}`, --time {args.time} per p, "
        f"W = {WINDOW['window_slope']:g}k + {WINDOW['window_offset']:g}, pilot `{args.pilot}` "
        f"({PILOTS[args.pilot][0].name})",
        "",
        "## gamma_hat",
        "",
        "| p | study | status | gamma_hat ± replicate se | Wilson 95% "
        "| final ladder | n/scale × reps | samples | min (pilot + draw) |",
        "|---|---|---|---|---|---|---|---|---|",
        *(g for g, _ in rows),
        "",
        "`n/scale × reps` = draws per scale in each replicate × independent replicates",
        "(`a..b` when n differs by scale: n at the smallest scale..n at the largest);",
        "`samples` = n summed over the scales × reps, the samples the final run produced.",
        "",
        "## omega1",
        "",
        "Both columns are the eq. (232) fit, pooled over replicates. **pilot** is the value in",
        "`constants.json` that sized the plan and the Wilson bound; **pilot converged** is that",
        "fit's own flag (`pilot.json[\"direct_fit\"]`). **final fit** is `answer.json[\"fit\"]`,",
        "refitted on the final ladder after the plan: no se is recorded, and since the plan",
        "deepens m0 until the correction has died, that refit is mostly noise (see",
        "`src/study/report.py`'s `wilson_inputs`). Read omega1 from the pilot.",
        "",
        "| p | omega1 pilot ± se | pilot converged | pilot scales | pilot n/scale × reps "
        "| pilot samples | omega1 final fit | a1 final fit | final scales "
        "| final n/scale × reps | final samples |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
        *(o for _, o in rows),
        "",
        "Scales are dyadic; `lo..hi (k)` = k scales from lo to hi. **pilot samples** counts the",
        "pilot's last doubling round only, the one omega1 was fitted on; earlier rounds are",
        "discarded redraws and `pilot.json` does not record them.",
    ])
    out = data / f"sweep_p_{args.tag}.md"
    out.write_text(table + "\n")
    print(f"\n{table}\n\n[sweep] summary -> {out}", flush=True)
    if failed:
        print(f"[sweep] nonzero exit for p = {failed}; see their logs", flush=True)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
