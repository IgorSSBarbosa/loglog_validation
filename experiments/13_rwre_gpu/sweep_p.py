"""Run `autopilot.py` on `rwre_gpu` over a sieve of p, one study per p, one after another.

Question: how does gamma_hat(p) behave on 02_rwre's sieve when the GPU buys each
point an hour instead of a CPU budget? At p = 1/2 the walk is srw (gamma = 1/2
exactly); below it 02_rwre measured effective exponents above 1/2, peaking near
p = 0.3 and still rising at k = 1024. Every arm gets the same pilot recipe and the
same wall clock, so what differs between studies is p alone.

The grid is 02_rwre's A6 sieve plus its headline p = 1/3, all in [0, 1/2]: |X_k| has
the same law at p and 1 - p (02_rwre/README.md), so the other half adds nothing.
p = 1/3 goes first because it is the point 02_rwre left open. The pilot recipe for
each p is `recipes/samples_calib_p0.5.json` with only `params.p` changed. A p whose
study already holds `autopilot.json` is skipped, so rerunning the same command
resumes an interrupted sweep. Arms run sequentially because they share one GPU.

    python3 experiments/13_rwre_gpu/sweep_p.py --tag 1h
    python3 experiments/13_rwre_gpu/sweep_p.py --tag 1h --p 1/3 0.2 -- --force

Anything after `--` is passed to every `autopilot.py` call unchanged.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from fractions import Fraction
from pathlib import Path

EXP = Path(__file__).resolve().parent
ROOT = EXP.parents[1]
TEMPLATE = EXP / "recipes" / "samples_calib_p0.5.json"
DATA = EXP / "data"

P_GRID = [1 / 3, 0.0, 0.1, 0.2, 0.3, 0.4, 0.45, 0.5]


def parse_p(s: str) -> float:
    """A p from the command line; fractions such as 1/3 are accepted."""
    p = float(Fraction(s))
    if not 0.0 <= p <= 1.0:
        raise argparse.ArgumentTypeError(f"p must be in [0, 1]; got {s}")
    return p


def label(p: float) -> str:
    """Short, filename-safe p for study and recipe names: 0.3333, not 0.3333333333333333."""
    return f"{p:.4g}"


def write_recipe(p: float) -> Path:
    recipe = json.loads(TEMPLATE.read_text())
    recipe["params"]["p"] = p
    recipe["_note"] = [
        f"GENERATED by experiments/13_rwre_gpu/sweep_p.py: {TEMPLATE.name} with only",
        "params.p changed. Edit the template or the script, not this file.",
    ]
    path = EXP / "recipes" / f"samples_sweep_p{label(p)}.json"
    path.write_text(json.dumps(recipe, indent=2) + "\n")
    return path


def summary_row(p: float, study: str, code: int | None, minutes: float | None) -> str:
    ap_path = DATA / study / "autopilot.json"
    if not ap_path.exists():
        return f"| {label(p)} | `{study}` | exit {code} | - | - | - | - |"
    ap = json.loads(ap_path.read_text())
    wall = "-" if minutes is None else f"{minutes:.1f}"
    if not ap.get("drawn"):
        return f"| {label(p)} | `{study}` | not drawn (gate) | - | - | - | {wall} |"
    answer = json.loads((DATA / study / "answer.json").read_text())
    lo, hi = answer["wilson"]["interval"]
    forced = " (forced)" if ap.get("forced") else ""
    return (f"| {label(p)} | `{study}` | drawn{forced} | {ap['gamma']:.5f} ± {answer['se']:.5f} "
            f"| [{lo:.4f}, {hi:.4f}] | {answer['scales'][0]}..{answer['scales'][-1]} | {wall} |")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--tag", required=True, help="study name suffix: sweep_p<p>_<tag>")
    ap.add_argument("--time", default="1h", help="autopilot --time for EACH p (default 1h)")
    ap.add_argument("--p", type=parse_p, nargs="+", default=P_GRID,
                    help="p values, run in this order; fractions like 1/3 are accepted")
    ap.add_argument("autopilot_args", nargs=argparse.REMAINDER,
                    help="after `--`: extra arguments for every autopilot.py call")
    args = ap.parse_args()
    extra = [a for a in args.autopilot_args if a != "--"]

    rows = []
    failed = []
    for p in args.p:
        study = f"sweep_p{label(p)}_{args.tag}"
        if (DATA / study / "autopilot.json").exists():
            print(f"[sweep] p={label(p)}: {study} already finished, skipping", flush=True)
            rows.append(summary_row(p, study, None, None))
            continue
        recipe = write_recipe(p)
        DATA.mkdir(exist_ok=True)
        log = DATA / f"{study}.log"
        cmd = [sys.executable, str(ROOT / "src/study/autopilot.py"), "-meta", str(recipe),
               "--study", study, "--data-root", str(DATA), "--time", args.time,
               "--no-progress", *extra]
        print(f"[sweep] p={label(p)}: {' '.join(cmd)}\n[sweep]   log -> {log}", flush=True)
        t0 = time.monotonic()
        # tee by hand: the log must survive a crash of this script, and the terminal
        # should still show the phase lines live.
        with log.open("w") as fh:
            proc = subprocess.Popen(cmd, cwd=ROOT, stdout=subprocess.PIPE,
                                    stderr=subprocess.STDOUT, text=True)
            for line in proc.stdout:
                sys.stdout.write(line)
                fh.write(line)
                fh.flush()
            code = proc.wait()
        minutes = (time.monotonic() - t0) / 60
        print(f"[sweep] p={label(p)}: exit {code} after {minutes:.1f} min", flush=True)
        rows.append(summary_row(p, study, code, minutes))
        if code != 0:
            failed.append(label(p))

    table = "\n".join([
        f"# rwre_gpu p sweep, tag `{args.tag}`, --time {args.time} per p",
        "",
        "| p | study | status | gamma_hat ± replicate se | Wilson 95% | final ladder | min |",
        "|---|---|---|---|---|---|---|",
        *rows,
    ])
    out = DATA / f"sweep_p_{args.tag}.md"
    out.write_text(table + "\n")
    print(f"\n{table}\n\n[sweep] summary -> {out}", flush=True)
    if failed:
        print(f"[sweep] nonzero exit for p = {failed}; see their logs", flush=True)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
