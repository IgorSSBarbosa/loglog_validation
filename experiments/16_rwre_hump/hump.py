"""Pilots and local slopes of `rwre_gpu` over a grid of p, to locate the hump in s(k).

Experiment 16 (user, 2026-09-30). For each p in the grid and each of two interleaved
dyadic ladders (2*2^j and 6*2^j), one `src/study/pilot.py` study at a flat n, on 15's
window W = 2k + 100. Each study's replicate means go through
`tools/local_slope.analyse` at rho = 2. The two ladders' slopes are then merged, each
at its pair's geometric midpoint, into one s(k) with a point every factor ~1.4. The
hump is the largest rise s(k_j) - s(k_i) over k_i < k_j, so a single noisy local
minimum can't hide the real one. Nothing here knows the conjectured positions. They
live in the README (ground rule 4).

A (p, ladder) whose study already holds `pilot.json` is not redrawn, so rerunning the
same command resumes an interrupted run, and on a finished one it only redoes the
analysis.

The second ladder starts at 6, not 3. On an odd k the walk's parity makes E|X_k|
jump: for srw, E|S_{2m-1}| = E|S_{2m}|. That put the 3 -> 6 slope at 0.37 in the
smoke run (2026-09-30).

    python3 experiments/16_rwre_hump/hump.py --tag n1e6 --seed 20260930
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

EXP = Path(__file__).resolve().parent
ROOT = EXP.parents[1]
sys.path.insert(0, str(ROOT))
from tools import local_slope as LS  # noqa: E402

P_GRID = [0.0, 0.05, 0.1, 0.125, 0.15, 0.175, 0.2, 0.225, 0.25, 0.275, 0.3]
#: ladder name -> its scales, base * 2^j. Both are even and both stop near 1024..1536.
LADDERS = {"a": [2 * 2**j for j in range(10)], "b": [6 * 2**j for j in range(9)]}
WINDOW = {"window_slope": 2.0, "window_offset": 100.0}
#: a hump counts as resolved when its amplitude exceeds this many se.
RESOLVED_SE = 3.0


def label(p: float) -> str:
    return f"{p:.4g}"


def write_recipe(p: float, ladder: str, n: int, seed: int) -> Path:
    recipe = {
        "kind": "samples",
        "model": "rwre_gpu",
        "params": {"p": p, "alpha": 0.5, **WINDOW},
        "scales": LADDERS[ladder],
        "n": n,
        "seed": seed,
        "_note": ["GENERATED by experiments/16_rwre_hump/hump.py. Edit the script, not this file."],
    }
    path = EXP / "recipes" / f"samples_hump_p{label(p)}_{ladder}.json"
    path.parent.mkdir(exist_ok=True)
    path.write_text(json.dumps(recipe, indent=2) + "\n")
    return path


def run_pilot(recipe: Path, study: str, data: Path, replicates: int, seed: int) -> None:
    data.mkdir(parents=True, exist_ok=True)
    log = data / f"{study}.log"
    cmd = [sys.executable, str(ROOT / "src/study/pilot.py"), "-meta", str(recipe),
           "--study", study, "--data-root", str(data), "--replicates", str(replicates),
           "--seed", str(seed), "--reuse-cost"]
    print(f"[hump] {study}: log -> {log}", flush=True)
    t0 = time.monotonic()
    with log.open("w") as fh:
        code = subprocess.run(cmd, cwd=ROOT, stdout=fh, stderr=subprocess.STDOUT).returncode
    print(f"[hump] {study}: exit {code} after {time.monotonic() - t0:.0f} s", flush=True)
    if code != 0:
        raise RuntimeError(f"{study}: pilot.py exited {code}; see {log}")


def ladder_slopes(pilot: dict) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """(k at the pair's geometric midpoint, s, se) for one study.

    se is the CLT's (`local_slope.clt_se`, from cv and n), not the replicate spread.
    With 4 replicates the spread's se has 3 dof and scatters by several x from one pair
    to the next. In the R = 2 smoke run that made a 3-se false hump at p = 0.
    """
    scales = pilot["scales"]
    reps = pilot["per_replicate"]
    y_by_scale = [[r["y_bar"][k] for r in reps] for k in range(len(scales))]
    cv = [float(np.mean([r["cv"][k] for r in reps])) for k in range(len(scales))]
    n = pilot["n"]
    ns = n if isinstance(n, list) else [n] * len(scales)
    res = LS.analyse(scales, y_by_scale, 2.0, cv=cv, n=ns)
    k = np.sqrt(np.asarray(scales[:-1], float) * np.asarray(scales[1:], float))
    return k, np.asarray(res["s"]), np.asarray(res["se_s_clt"])


def find_hump(k: np.ndarray, s: np.ndarray, se: np.ndarray) -> dict:
    """The largest rise s[j] - s[i] over i < j; None where s never rises."""
    rise = s[None, :] - s[:, None]
    rise[np.tril_indices(len(s))] = -np.inf
    i, j = np.unravel_index(int(np.argmax(rise)), rise.shape)
    amp = float(rise[i, j])
    if amp <= 0:
        return {"k_min": None, "k_max": None, "amp": 0.0, "amp_se": None, "resolved": False}
    amp_se = float(np.hypot(se[i], se[j]))
    return {"k_min": float(k[i]), "k_max": float(k[j]), "amp": amp,
            "amp_se": amp_se, "resolved": bool(amp > RESOLVED_SE * amp_se)}


def plot(curves: dict, out: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(8, 5.5))
    cmap = plt.get_cmap("viridis")
    ps = sorted(curves)
    for t, p in enumerate(ps):
        k, s, se = curves[p]
        c = cmap(t / max(len(ps) - 1, 1))
        ax.errorbar(k, s, yerr=se, color=c, marker="o", ms=3, lw=1, capsize=0, label=f"p={label(p)}")
    ax.set_xscale("log", base=2)
    ax.set_xlabel("k (geometric midpoint of the pair)")
    ax.set_ylabel("local slope s(k)")
    ax.axhline(0.5, color="0.6", lw=0.8, ls=":")
    ax.legend(fontsize=7, ncol=2)
    ax.set_title("rwre_gpu, W = 2k + 100: local slopes, ladders 2*2^j and 6*2^j merged")
    fig.tight_layout()
    fig.savefig(out, dpi=130)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--tag", required=True, help="study name suffix: hump_p<p>_<ladder>_<tag>")
    ap.add_argument("--seed", type=int, required=True,
                    help="base seed; study t of the grid gets seed + t")
    ap.add_argument("--n", type=int, default=1_000_000, help="draws per scale per replicate")
    ap.add_argument("--replicates", type=int, default=4)
    ap.add_argument("--p", type=float, nargs="+", default=P_GRID)
    ap.add_argument("--data-root", type=Path, default=EXP / "data")
    args = ap.parse_args()
    data = args.data_root.resolve()

    curves, rows = {}, []
    for ip, p in enumerate(args.p):
        parts = []
        for il, ladder in enumerate(LADDERS):
            study = f"hump_p{label(p)}_{ladder}_{args.tag}"
            seed = args.seed + 2 * ip + il
            if not (data / study / "pilot.json").exists():
                run_pilot(write_recipe(p, ladder, args.n, seed), study, data, args.replicates, seed)
            parts.append(ladder_slopes(json.loads((data / study / "pilot.json").read_text())))
        k = np.concatenate([q[0] for q in parts])
        order = np.argsort(k)
        k, s, se = (np.concatenate([q[i] for q in parts])[order] for i in range(3))
        curves[p] = (k, s, se)
        rows.append((p, find_hump(k, s, se)))

    out_png = data / f"hump_{args.tag}.png"
    plot(curves, out_png)
    lines = [
        f"# rwre_gpu hump, tag `{args.tag}`: W = 2k + 100, ladders "
        f"{LADDERS['a'][0]}..{LADDERS['a'][-1]} and {LADDERS['b'][0]}..{LADDERS['b'][-1]}, n = {args.n:,} × {args.replicates} per scale",
        "",
        f"Hump: the largest rise s(k_max) - s(k_min) with k_min < k_max; resolved if "
        f"amplitude > {RESOLVED_SE:g} se. k is the pair's geometric midpoint.",
        "",
        "| p | k_min | k_max | amplitude ± se | resolved |",
        "|---|---|---|---|---|",
    ]
    for p, h in rows:
        if h["k_min"] is None:
            lines.append(f"| {label(p)} | - | - | none (monotone) | False |")
        else:
            lines.append(f"| {label(p)} | {h['k_min']:.1f} | {h['k_max']:.1f} "
                         f"| {h['amp']:.4f} ± {h['amp_se']:.4f} | {h['resolved']} |")
    lines += ["", "## s(k) ± se", ""]
    for p in sorted(curves):
        k, s, se = curves[p]
        lines.append(f"- p={label(p)}: " + ", ".join(
            f"{a:.1f}: {b:.4f}±{c:.4f}" for a, b, c in zip(k, s, se)))
    text = "\n".join(lines) + "\n"
    (data / f"hump_{args.tag}.md").write_text(text)
    (data / f"hump_{args.tag}.json").write_text(json.dumps(
        {"produced_by": "experiments/16_rwre_hump/hump.py", "args": vars(args) | {"data_root": str(data)},
         "humps": {label(p): h for p, h in rows},
         "curves": {label(p): {"k": c[0].tolist(), "s": c[1].tolist(), "se": c[2].tolist()}
                    for p, c in curves.items()}}, indent=1, default=str))
    print(text + f"\n[hump] figure -> {out_png}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
